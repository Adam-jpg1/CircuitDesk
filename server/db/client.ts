// Where the community's database is, and bringing its schema up to date.
//
// Production: DATABASE_URL, a hosted Postgres (Neon), through node-postgres.
// The data lives with the database provider, so a deploy, a restart or the
// service sleeping touches none of it.
//
// Without DATABASE_URL — local development and the tests — the same schema
// and the same SQL run on PGlite, Postgres compiled to WebAssembly, kept in
// COMMUNITY_DATA_DIR/pglite (or in memory with COMMUNITY_DATA_DIR=memory).
// One code path, one set of migrations, whichever is underneath.
//
// Migrations are the committed files in server/db/migrations, generated by
// drizzle-kit from schema.ts. They are applied at startup under a Postgres
// advisory lock, so two instances starting together cannot both apply one.
// Applied migrations are recorded in drizzle.__drizzle_migrations and never
// run twice; nothing here drops or resets a table.

import { existsSync, statSync } from 'node:fs';
import { mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import type { PgDatabase, PgQueryResultHKT } from 'drizzle-orm/pg-core';
import * as schema from './schema.js';

export type Db = PgDatabase<PgQueryResultHKT, typeof schema>;

export interface Database {
  db: Db;
  kind: 'postgres' | 'pglite';
  /** Whether the data outlives this process's container. */
  persistent: boolean;
  /** Host and database name, or the PGlite directory. Never a password. */
  location: string;
  close(): Promise<void>;
}

/** Any number will do, as long as nothing else in the database uses it. */
const MIGRATION_LOCK = 4_242_031;

/** The migrations folder, from the sources (tsx) or from dist-server (node). */
export function migrationsFolder(): string {
  const here = path.dirname(fileURLToPath(import.meta.url));
  const candidates = [path.join(here, 'migrations'), path.resolve(here, '../../server/db/migrations')];
  const found = candidates.find((dir) => existsSync(path.join(dir, 'meta', '_journal.json')));
  if (!found) throw new Error(`No database migrations found (looked in ${candidates.join(', ')}).`);
  return found;
}

/** The nearest directory that exists at or above `dir`. */
function existingAncestor(dir: string): string {
  let at = path.resolve(dir);
  while (!existsSync(at)) {
    const up = path.dirname(at);
    if (up === at) break;
    at = up;
  }
  return at;
}

/** Whether `dir` sits on a different device from the root filesystem: a mounted volume. */
export function onMountedVolume(dir: string): boolean {
  try {
    return statSync(existingAncestor(dir)).dev !== statSync('/').dev;
  } catch {
    return false;
  }
}

/** "user:secret@host:5432/db?..." -> "host/db", for logs and status. */
export function describeUrl(url: string): string {
  try {
    const u = new URL(url);
    return `${u.hostname}${u.pathname}`;
  } catch {
    return 'postgres';
  }
}

async function openPostgres(url: string): Promise<Database> {
  const { Pool } = (await import('pg')).default;
  const { drizzle } = await import('drizzle-orm/node-postgres');
  const { migrate } = await import('drizzle-orm/node-postgres/migrator');
  const pool = new Pool({
    connectionString: url,
    max: Number(process.env.DATABASE_POOL_MAX ?? 5),
    // Close idle connections quickly: a hosted database that scales to zero
    // (Neon) can only suspend once nothing is connected.
    idleTimeoutMillis: 10_000,
    // A suspended Neon compute takes a few seconds to wake.
    connectionTimeoutMillis: 20_000,
  });
  // An idle connection the provider closes must not take the server down.
  pool.on('error', (err) => console.error('[CircuitDesk] database connection dropped:', err.message));

  // Migrate on one connection holding the lock for the whole run.
  const client = await pool.connect();
  try {
    await client.query('SELECT pg_advisory_lock($1)', [MIGRATION_LOCK]);
    try {
      await migrate(drizzle(client, { schema }), { migrationsFolder: migrationsFolder() });
    } finally {
      await client.query('SELECT pg_advisory_unlock($1)', [MIGRATION_LOCK]);
    }
  } finally {
    client.release();
  }
  return {
    db: drizzle(pool, { schema }) as unknown as Db,
    kind: 'postgres',
    persistent: true,
    location: describeUrl(url),
    close: () => pool.end(),
  };
}

async function openPglite(dir: string | null): Promise<Database> {
  const { PGlite } = await import('@electric-sql/pglite');
  const { drizzle } = await import('drizzle-orm/pglite');
  const { migrate } = await import('drizzle-orm/pglite/migrator');
  if (dir) await mkdir(dir, { recursive: true });
  const client = new PGlite(dir ?? undefined);
  const db = drizzle(client, { schema });
  await migrate(db, { migrationsFolder: migrationsFolder() });
  return {
    db: db as unknown as Db,
    kind: 'pglite',
    persistent: dir !== null && (process.env.COMMUNITY_DISK_PERSISTENT === '1' || onMountedVolume(dir)),
    location: dir ?? 'memory',
    close: () => client.close(),
  };
}

/** Opens the configured database and applies any pending migrations. */
export async function openDatabase(): Promise<Database> {
  const url = process.env.DATABASE_URL?.trim();
  if (url) return openPostgres(url);
  if (process.env.COMMUNITY_DATA_DIR === 'memory') return openPglite(null);
  const base = process.env.COMMUNITY_DATA_DIR || path.resolve(process.cwd(), '.community-data');
  return openPglite(path.join(base, 'pglite'));
}
